/// One recognised artifact directory name.
///
/// `name` is what the walk matches, `kind` / `ecosystem` are what the record
/// reports, `rebuild_markers` are files in the project root that prove the
/// directory is regenerable (empty = the kind is regenerable by convention),
/// `rebuild_how` becomes the reason's evidence, and `generic_name` marks names
/// that are common outside build output (`build`, `dist`, `coverage`, …) and
/// therefore also need the authored-content check.
#[derive(Debug, Clone, Copy)]
pub struct ArtifactKind {
    pub name: &'static str,
    pub kind: &'static str,
    pub ecosystem: &'static str,
    pub rebuild_markers: &'static [&'static str],
    pub rebuild_how: &'static str,
    pub generic_name: bool,
}

