/// The artifact kind a directory name maps to, or `None` when the name is not a
/// recognised artifact directory.
pub fn lookup_kind(name: &str) -> Option<&'static ArtifactKind> {
    ARTIFACT_KINDS.iter().find(|spec| spec.name == name)
}

/// Injection points for one artifact scan.
///
/// Mirrors [`crate::worktree::WorktreeCheckOptions`]: everything that depends on the
/// clock, on a measurement, or on user policy is passed in, so the decision logic is
/// a pure function of the filesystem and of Git output.
#[derive(Debug, Clone)]
pub struct ArtifactScanOptions {
    /// How deep below a worktree root a candidate may sit (settings.max_depth).
    pub max_depth: usize,
    /// Budget for one size measurement (settings.per_dir_timeout_sec).
    pub per_dir_timeout: Duration,
    /// Activity window in days (settings.active_days).
    pub recent_activity_days: u32,
    /// Whitelist rules, already expanded to absolute paths by the caller.
    pub whitelist: Vec<PathBuf>,
    /// Injected clock, so "recent activity" is testable.
    pub now: SystemTime,
    /// When set, the scan stops adding artifacts once the budget is spent and
    /// reports the unscanned remainder as a warning instead of guessing.
    pub budget_deadline: Option<Instant>,
    /// Extra budget for the credential walk, on top of half of `per_dir_timeout`.
    ///
    /// Only set by tests: a test that drives `per_dir_timeout` to zero to make the
    /// *size* measurement time out would otherwise also starve the credential walk,
    /// and the two cannot be exercised apart. `None` in production, where the
    /// credential walk simply takes its half of `per_dir_timeout`.
    pub credential_budget: Option<Duration>,
}

impl Default for ArtifactScanOptions {
    fn default() -> Self {
        Self {
            max_depth: 6,
            per_dir_timeout: Duration::from_secs(30),
            recent_activity_days: 7,
            whitelist: Vec::new(),
            now: SystemTime::now(),
            budget_deadline: None,
            credential_budget: None,
        }
    }
}

/// Result of one artifact scan.
pub struct ArtifactScanResult {
    pub records: Vec<ArtifactRecord>,
    /// Scanner-produced notes (a size measurement that timed out, a budget that
    /// ran out). They travel with the snapshot as data, not as UI chrome.
    pub warnings: Vec<String>,
}

/// Walks every worktree root and checks each recognised artifact directory.
///
/// `runner` answers the Git questions; the filesystem answers the rest. A root
/// that no longer exists (a prunable worktree) is skipped: there is nothing to
/// scan and nothing to delete.
pub fn scan_artifacts(
    runner: &dyn GitRunner,
    roots: &[PathBuf],
    opts: &ArtifactScanOptions,
) -> ArtifactScanResult {
    let mut records: Vec<ArtifactRecord> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let mut budget_spent = false;

    for root in roots {
        // A prunable worktree has no directory left, so it has no artifacts. Any
        // other stat failure is not evidence of absence, so only `NotFound`
        // skips (the same rule the worktree checks use).
        match std::fs::metadata(root) {
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
            Err(_) => continue,
        }

        for candidate in collect_candidates(root, opts.max_depth) {
            if let Some(deadline) = opts.budget_deadline {
                if Instant::now() >= deadline {
                    warnings.push(format!(
                        "the scan budget ran out; artifact scanning stopped at {} ({} directories checked so far)",
                        candidate.path.display(),
                        records.len()
                    ));
                    budget_spent = true;
                    break;
                }
            }
            let Some(spec) = lookup_kind(&candidate.name) else {
                continue;
            };
            let (record, mut notes) = check_artifact(runner, root, &candidate.path, spec, opts);
            warnings.append(&mut notes);
            records.push(record);
        }
        if budget_spent {
            break;
        }
    }

    ArtifactScanResult { records, warnings }
}

/// A directory whose name matched a recognised artifact kind.
struct Candidate {
    path: PathBuf,
    name: String,
}

/// Upper bound on directory entries visited per worktree root. A repository with
/// more entries than this is not scanned completely, and the measurement reports
/// `None` rather than a partial number that would look exact.
const MAX_WALK_ENTRIES: usize = 2_000_000;

/// Collects artifact candidate directories under `root`, breadth-first by depth.
///
/// The walk never enters `.git` and never descends into a recognised artifact
/// directory: `node_modules/.bin` is not a second artifact, and `node_modules`
/// is never treated as a project root (D8).
fn collect_candidates(root: &Path, max_depth: usize) -> Vec<Candidate> {
    let mut out: Vec<Candidate> = Vec::new();
    let mut stack: Vec<(PathBuf, usize)> = vec![(root.to_path_buf(), 0)];
    let mut visited: usize = 0;

    while let Some((dir, depth)) = stack.pop() {
        // An unreadable directory is not evidence that nothing is inside it.
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            visited += 1;
            if visited > MAX_WALK_ENTRIES {
                return out;
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            let path = entry.path();
            // `DirEntry::metadata` does not follow symlinks, which is what the
            // symlink checks below need.
            let is_dir = entry.metadata().is_ok_and(|meta| meta.is_dir());

            if lookup_kind(&name).is_some() {
                out.push(Candidate { path, name });
                continue;
            }
            if is_dir && name != ".git" && name != ".hg" && name != ".svn" && depth < max_depth {
                stack.push((path, depth + 1));
            }
        }
    }
    out
}

/// Checks one candidate directory and assembles its [`ArtifactRecord`].
///
/// Returns the record together with scanner notes (an unmeasurable size). The
/// verdict is derived from the reasons by [`SafetyAssessment::from_reasons`]
/// (D2); this function never scores a level on its own.
pub fn check_artifact(
    runner: &dyn GitRunner,
    root: &Path,
    dir: &Path,
    spec: &ArtifactKind,
    opts: &ArtifactScanOptions,
) -> (ArtifactRecord, Vec<String>) {
    check_artifact_with_credential_limit(runner, root, dir, spec, opts, CREDENTIAL_SCAN_LIMIT)
}

/// [`check_artifact`] with the credential walk's entry bound as a parameter, so the
/// truncation branch is reachable from a small fixture.
fn check_artifact_with_credential_limit(
    runner: &dyn GitRunner,
    root: &Path,
    dir: &Path,
    spec: &ArtifactKind,
    opts: &ArtifactScanOptions,
    credential_limit: usize,
) -> (ArtifactRecord, Vec<String>) {
    let mut reasons: Vec<Reason> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let dir_text = dir.display().to_string();

    // ---- symlink: never follow, never delete through the link ----
    let link_meta = std::fs::symlink_metadata(dir);
    let is_symlink = link_meta.as_ref().is_ok_and(|m| m.file_type().is_symlink());
    let mut symlink_target: Option<String> = None;
    if is_symlink {
        let target = std::fs::canonicalize(dir).ok();
        let root_resolved = std::fs::canonicalize(root).unwrap_or_else(|_| root.to_path_buf());
        match target {
            Some(target) if !target.starts_with(&root_resolved) => {
                symlink_target = Some(target.display().to_string());
                reasons.push(Reason::blocking(
                    ReasonCode::AfSymlinkOutside,
                    "symlink pointing outside the project",
                    format!(
                        "target {} is outside the project root {}; deleting it would damage a shared directory",
                        target.display(),
                        root.display()
                    ),
                ));
            }
            Some(target) => {
                symlink_target = Some(target.display().to_string());
                reasons.push(Reason::review(
                    ReasonCode::AfCannotVerify,
                    "could not complete the check",
                    format!(
                        "symlink target {} is inside the project; deleting the link does not remove the target",
                        target.display()
                    ),
                ));
            }
            None => {
                reasons.push(Reason::review(
                    ReasonCode::AfCannotVerify,
                    "could not complete the check",
                    format!("the symlink target of {dir_text} cannot be resolved"),
                ));
            }
        }
    }

    // ---- whitelist: a rule protects the path completely ----
    if let Some(rule) = whitelist_hit(dir, &opts.whitelist) {
        reasons.push(Reason::blocking(
            ReasonCode::AfWhitelisted,
            "protected by a whitelist rule",
            format!("matches the whitelist rule {}", rule.display()),
        ));
    }

    // ---- nested repository: deleting it would destroy history ----
    if !is_symlink && dir.join(".git").exists() {
        reasons.push(Reason::blocking(
            ReasonCode::AfNestedGit,
            "contains a nested Git repository",
            "a .git directory was found inside; deleting it would destroy that repository's history",
        ));
    }

    // ---- Git tracking: tracked content is not a build artifact (D7) ----
    let mut git_tracked: Option<bool> = None;
    if !is_symlink {
        match runner.run(root, &["ls-files", "--", &dir_text]) {
            Ok(output) if output.success() => {
                let tracked = output
                    .stdout
                    .lines()
                    .filter(|line| !line.trim().is_empty())
                    .count();
                git_tracked = Some(tracked > 0);
                if tracked > 0 {
                    reasons.push(Reason::blocking(
                        ReasonCode::AfGitTracked,
                        "the directory contains files committed to the repository",
                        format!("git ls-files matches {tracked} files, so it is not a pure build artifact"),
                    ));
                }
            }
            Ok(output) => reasons.push(cannot_verify(&format!(
                "git ls-files exited with {:?}: {}",
                output.code,
                output.stderr.trim()
            ))),
            Err(error) => reasons.push(cannot_verify(&format!("git ls-files failed: {error}"))),
        }
    }

    // ---- Git ignore status ----
    let mut git_ignored: Option<bool> = None;
    if !is_symlink {
        match runner.run(root, &["check-ignore", "-v", "--", &dir_text]) {
            Ok(output) if output.success() => {
                git_ignored = Some(true);
                let evidence = parse_ignore_source(&output.stdout)
                    .unwrap_or_else(|| "git check-ignore reports it as ignored".to_string());
                reasons.push(Reason::safe(
                    ReasonCode::AfGitIgnored,
                    "ignored by .gitignore",
                    evidence,
                ));
            }
            // Exit 1 means "not ignored", which is a real answer, not a failure.
            Ok(output) if output.code == Some(1) => git_ignored = Some(false),
            Ok(output) => reasons.push(cannot_verify(&format!(
                "git check-ignore exited with {:?}: {}",
                output.code,
                output.stderr.trim()
            ))),
            Err(error) => reasons.push(cannot_verify(&format!("git check-ignore failed: {error}"))),
        }
    }

    // ---- credentials: deleting this would take the keys with it ----
    //
    // Checked before `authored_content`, because the files it looks for are usually
    // *ignored* by Git: `.env` and `id_rsa` are the entries a `.gitignore` exists to
    // list, so `git status` reports nothing and the authored-content check cannot fire
    // for exactly the files this is about.
    //
    // The check walks the directory, bounded. Passing the bound is a `Review` with
    // the count in the evidence rather than a silent pass: a partial walk cannot
    // claim the directory is clean, but it is not the same as being unable to look
    // at all, and treating the two alike would leave every large `node_modules`
    // permanently unverifiable (D3, without turning the tool into noise).
    if !is_symlink {
        // The same budget the size walk got, halved: this is a second pass over
        // the same tree, so letting it have the full budget doubles what one
        // directory can cost the executor.
        match credential_in_within(dir, credential_limit, credential_budget(opts)) {
            CredentialScan::Complete(Some(name)) => reasons.push(Reason::blocking(
                ReasonCode::AfCredentials,
                "contains what looks like a credential file",
                format!("{name} is inside; deleting the directory would delete it too"),
            )),
            CredentialScan::Complete(None) => {}
            CredentialScan::Truncated { scanned } => reasons.push(Reason::review(
                ReasonCode::AfCannotVerify,
                "could not finish checking for credentials",
                format!(
                    "looked at {scanned} entries before the time limit, without covering the whole directory; a credential further inside would not have been found"
                ),
            )),
            CredentialScan::Failed(error) => reasons.push(cannot_verify(&format!(
                "could not list {dir_text} to check for credentials: {error}"
            ))),
        }
    }

    // ---- authored content: a generic name holding hand-written files ----
    if spec.generic_name && !is_symlink && git_tracked != Some(true) {
        match runner.run(
            root,
            &[
                "status",
                "--porcelain",
                "--untracked-files=all",
                "--",
                &dir_text,
            ],
        ) {
            Ok(output) if output.success() => {
                // `--porcelain` (v1) marks an untracked entry with `??`; the
                // `? ` form belongs to `--porcelain=v2` and would never match
                // here, silently disabling this check.
                let untracked = output
                    .stdout
                    .lines()
                    .filter(|line| line.starts_with("??"))
                    .count();
                if untracked > 0 {
                    reasons.push(Reason::blocking(
                        ReasonCode::AfAuthoredContent,
                        "contains hand-written content",
                        format!(
                            "{untracked} files inside are neither tracked by Git nor ignored; they look like authored content"
                        ),
                    ));
                }
            }
            Ok(output) => reasons.push(cannot_verify(&format!(
                "git status exited with {:?}: {}",
                output.code,
                output.stderr.trim()
            ))),
            Err(error) => reasons.push(cannot_verify(&format!("git status failed: {error}"))),
        }
    }

    // ---- size, file count, and newest modification ----
    let measurement = if is_symlink {
        // Never walk through a symlink: the target may be a shared store whose
        // size says nothing about this project.
        Measurement::unknown()
    } else {
        measure_dir(dir, opts.per_dir_timeout)
    };
    if measurement.vanished {
        // Not a timing problem, and saying it was one would send the reader
        // looking for a slow disk instead of a directory that has to go.
        warnings.push(format!(
            "{dir_text} is no longer on disk; it is reported as unmeasurable rather than empty"
        ));
    } else if measurement.bytes.is_none() && !is_symlink {
        warnings.push(format!(
            "size measurement of {} did not complete within {}s; the size is recorded as unknown",
            dir_text,
            opts.per_dir_timeout.as_secs()
        ));
    }
    let last_updated_at = measurement.newest.map(format_rfc3339);

    // ---- emptiness ----
    //
    // Gated on the measurement having *completed*, not on the file count alone: an
    // unmeasurable directory also reports `files == 0`, and reading that as "empty"
    // handed a 50-file directory an `af.empty` Safe reason the moment its size
    // measurement timed out. "Could not measure" is not "empty" (D3), and the size
    // walk already said so in `size_bytes: null` plus a warning.
    //
    // The gate covers all three unmeasurable outcomes, because the walk now
    // separates them from a walk that really did read an empty directory: a
    // timeout, a directory that cannot be read, and a directory that is gone.
    // Only the last of those left `Some(0)` behind, which is why this test existed
    // and still did not catch it.
    if !is_symlink && measurement.bytes.is_some() && measurement.files == 0 {
        reasons.push(Reason::safe(
            ReasonCode::AfEmpty,
            "the directory is empty",
            "it contains no files",
        ));
    }

    // ---- rebuildability ----
    if spec.rebuild_markers.is_empty() {
        reasons.push(Reason::safe(
            ReasonCode::AfRebuildable,
            "regenerable directory",
            spec.rebuild_how.to_string(),
        ));
    } else {
        let found = spec
            .rebuild_markers
            .iter()
            .find(|marker| root.join(marker).exists());
        match found {
            Some(marker) => reasons.push(Reason::safe(
                ReasonCode::AfRebuildable,
                "regenerable directory",
                format!("{marker} exists; {}", spec.rebuild_how),
            )),
            None => reasons.push(Reason::review(
                ReasonCode::AfCannotVerify,
                "could not complete the check",
                format!(
                    "no build manifest ({}) at the project root; cannot confirm the directory is regenerable",
                    spec.rebuild_markers.join(" / ")
                ),
            )),
        }
    }

    // ---- activity ----
    if let Some(newest) = measurement.newest {
        let age_days = elapsed_days(opts.now, newest);
        if age_days <= u64::from(opts.recent_activity_days) {
            reasons.push(Reason::review(
                ReasonCode::AfRecentActivity,
                "changed recently",
                format!("last activity: {}", humanize_days(age_days)),
            ));
        }
    }

    let record = ArtifactRecord {
        path: dir_text,
        kind: spec.kind.to_string(),
        ecosystem: spec.ecosystem.to_string(),
        project_root: root.display().to_string(),
        worktree_path: Some(root.display().to_string()),
        size_bytes: measurement.bytes,
        file_count: measurement.files,
        last_updated_at,
        git_ignored,
        git_tracked,
        is_symlink,
        symlink_target,
        safety: SafetyAssessment::from_reasons(reasons),
    };
    (record, warnings)
}

/// A `cannot_verify` reason for an artifact check that could not be completed.
fn cannot_verify(evidence: &str) -> Reason {
    Reason::review(
        ReasonCode::AfCannotVerify,
        "could not complete the check",
        evidence.to_string(),
    )
}

/// How many entries the credential check looks at before it gives up.
///
/// The hard ceiling on entries the credential check will look at.
///
/// **measured** on this machine, walking every entry with `read_dir` + `lstat`:
/// a 5,786-entry `node_modules` takes 76ms, a 49,913-entry one 795ms, a 138,857-entry
/// one 859ms and a 237,522-entry one 1.63s. Entry count was never the thing worth
/// bounding — time is, and the caller's `per_dir_timeout` already bounds that.
///
/// Counting entries is kept only as a last-resort ceiling for a pathological tree
/// (a network mount, a loop of bind mounts) where a per-directory budget would
/// otherwise be spent entry by entry rather than in wall-clock time. It is set far
/// above any real dependency tree so it is never the reason a normal `node_modules`
/// cannot be checked: an earlier bound of 50,000 made every repository whose
/// dependencies exceeded it permanently `cannot_verify`, which read on the result
/// page as dozens of unexplained "skipped" rows.
const CREDENTIAL_SCAN_LIMIT: usize = 1_000_000;

/// The budget the credential walk gets for one directory.
///
/// Half of the per-directory budget, because it is a second pass over the tree the
/// size walk already read: giving it the whole budget would let one directory cost
/// the executor twice what the user allowed. Overridable in tests, so a test can
/// starve the size walk without also starving this one.
fn credential_budget(opts: &ArtifactScanOptions) -> Duration {
    opts.credential_budget
        .unwrap_or_else(|| opts.per_dir_timeout / 2)
}

/// The outcome of looking for credential files in a directory.
#[derive(Debug, PartialEq, Eq)]
enum CredentialScan {
    /// The whole directory was walked; `name` is the hit, relative to the directory.
    Complete(Option<String>),
    /// The walk hit its ceiling, so the rest of the tree was never looked at.
    /// `scanned` says how far it got, which is what the user is told.
    Truncated { scanned: usize },
    /// A directory could not be read at all. Carries the message rather than the
    /// `io::Error` itself, so the outcome stays comparable in tests.
    Failed(String),
}

/// A credential-looking entry inside `dir`, named relative to `dir`, if there is one.
///
/// Walks rather than looking only at the top level: a secret is as likely to sit in
/// `config/` as in the directory itself, and the integration test found exactly that
/// when the `.env` was written one directory down. Symlinks are not followed
/// (`DirEntry::metadata` is `lstat`), so the walk cannot leave the directory, and
/// `.git` is skipped so a nested repository is not walked for nothing.
///
/// Bounded twice, and both bounds matter. The ceiling is a last-resort guard
/// against a pathological tree. The deadline is the one that does the real work:
/// this walk runs *in addition to* the size walk, so without a deadline of its own
/// a slow directory was checked for size, then checked again for credentials with
/// nothing to stop the second pass, and the executor spent twice its budget on one
/// item. Passing the deadline is the same partial-walk outcome as the ceiling.
/// Bounded by a ceiling (a last-resort guard for a pathological tree) and by a
/// deadline, which is what the caller really controls: `per_dir_timeout` is the
/// budget the user set for one directory.
fn credential_in_within(dir: &Path, limit: usize, budget: Duration) -> CredentialScan {
    let started = Instant::now();
    let mut visited = 0usize;
    let mut stack = vec![dir.to_path_buf()];
    while let Some(current) = stack.pop() {
        let entries = match std::fs::read_dir(&current) {
            Ok(entries) => entries,
            Err(error) => return CredentialScan::Failed(error.to_string()),
        };
        for entry in entries {
            let entry = match entry {
                Ok(entry) => entry,
                Err(error) => return CredentialScan::Failed(error.to_string()),
            };
            visited += 1;
            if visited > limit || started.elapsed() > budget {
                return CredentialScan::Truncated {
                    scanned: visited - 1,
                };
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            if looks_like_credential(&name) {
                let relative = entry
                    .path()
                    .strip_prefix(dir)
                    // Fall back to the absolute path: it only happens if the entry is
                    // somehow not below the directory it was listed from, and an
                    // absolute path is still something the user can act on.
                    .map_or_else(|_| entry.path(), Path::to_path_buf);
                return CredentialScan::Complete(Some(relative.display().to_string()));
            }
            if name != ".git" && entry.metadata().is_ok_and(|meta| meta.is_dir()) {
                stack.push(entry.path());
            }
        }
    }
    CredentialScan::Complete(None)
}

/// Whether a file name is one people keep secrets in.
///
/// A table rather than a heuristic. A false positive costs one item the user has to
/// confirm by hand; a false negative costs the secrets. So the table is generous —
/// `.env.example` is matched too, because a template that was filled in where it
/// stood is a real mistake. A public key is the one thing left out: `id_rsa.pub` is
/// meant to be shared, and the private half beside it is caught by its own name.
///
/// Not covered, on purpose: a secret whose name gives nothing away — `config.json`
/// holding an API key reads as a config file. That one is recorded as an open item
/// rather than guessed at here.
fn looks_like_credential(name: &str) -> bool {
    const EXACT: &[&str] = &[
        ".netrc",
        ".npmrc",
        ".pypirc",
        ".htpasswd",
        ".git-credentials",
        "credentials",
        "credentials.json",
        "id_rsa",
        "id_dsa",
        "id_ecdsa",
        "id_ed25519",
    ];
    const EXTENSIONS: &[&str] = &[
        "pem",
        "key",
        "p12",
        "pfx",
        "jks",
        "keystore",
        "kdbx",
        "mobileprovision",
        "ovpn",
    ];

    let lower = name.to_lowercase();
    if EXACT.contains(&lower.as_str()) {
        return true;
    }

    // `.env` and every variant of it: `.env.local`, `.env.production`, `.env.example`.
    if lower == ".env" || lower.starts_with(".env.") {
        return true;
    }

    // `Path::extension` rather than a string suffix. Comparing an extension with
    // `ends_with` is how a `.JSON` slips past, and this way the answer does not depend
    // on the lowercasing above having gone right.
    let extension = Path::new(&lower).extension().and_then(|ext| ext.to_str());
    if extension.is_some_and(|ext| EXTENSIONS.contains(&ext)) {
        return true;
    }

    // Service-account files are named after the account: `service-account-prod.json`.
    lower.starts_with("service-account") && extension == Some("json")
}

/// Parses `git check-ignore -v` output (`<source>:<line>:<pattern>\t<path>`) into
/// the `.gitignore:12` form the UI shows as evidence.
fn parse_ignore_source(stdout: &str) -> Option<String> {
    let line = stdout.lines().next()?;
    let (source, _rest) = line.split_once('\t')?;
    let mut parts = source.splitn(3, ':');
    let file = parts.next()?;
    let number = parts.next()?;
    if file.is_empty() || number.is_empty() {
        return None;
    }
    Some(format!("{file}:{number}"))
}

/// One size measurement.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Measurement {
    /// `None` = unmeasurable (timeout, an entry-count cap, or a directory that
    /// could not be read), which must stay distinguishable from `0`
    /// (development contract section 3).
    pub bytes: Option<u64>,
    /// File count; `0` also covers "not counted", which the UI shows as unknown.
    pub files: u64,
    /// Newest modification time seen, when the walk completed.
    pub newest: Option<SystemTime>,
    /// The directory itself is gone, as opposed to merely unreadable.
    ///
    /// The two are different facts and want different sentences: a vanished
    /// directory needs nothing doing, an unreadable one needs somebody to fix a
    /// permission. Reporting either as "0 bytes, 0 files" called it empty, and
    /// `af.empty` is a Safe verdict — deletable without confirmation.
    pub vanished: bool,
}

impl Measurement {
    const fn unknown() -> Self {
        Self {
            bytes: None,
            files: 0,
            newest: None,
            vanished: false,
        }
    }

    /// The directory is not on disk any more.
    ///
    /// Deliberately not `unknown()`: nothing failed to be read, and calling it a
    /// timeout would send the reader looking for a slow disk instead of a
    /// directory they have to decide about.
    const fn vanished() -> Self {
        Self {
            bytes: None,
            files: 0,
            newest: None,
            vanished: true,
        }
    }
}

/// Measures a directory on a worker thread with a timeout.
///
/// The worker is abandoned when the budget expires: the numbers it would report
/// are unknown, and a partial sum would look exact (D3). Symlinks are never
/// followed, so a link cycle cannot make the walk run forever.
pub fn measure_dir(path: &Path, timeout: Duration) -> Measurement {
    let (sender, receiver) = mpsc::channel();
    let owned = path.to_path_buf();
    let worker = std::thread::spawn(move || {
        let _ = sender.send(walk_size(&owned));
    });
    let measurement = match receiver.recv_timeout(timeout) {
        Ok(measurement) => measurement,
        // The worker keeps running in the background and its result is dropped:
        // reporting a partial size would be worse than reporting none.
        Err(_) => Measurement::unknown(),
    };
    // Joining would block for as long as the walk takes, which is exactly what
    // the timeout exists to avoid; the thread holds no borrowed state.
    drop(worker);
    measurement
}

fn walk_size(root: &Path) -> Measurement {
    walk_size_with_cap(root, MAX_WALK_ENTRIES)
}

/// The entry cap is a parameter so the over-limit branch can be exercised by a
/// three-entry fixture instead of a two-million-entry one.
fn walk_size_with_cap(root: &Path, cap: usize) -> Measurement {
    let mut bytes: u64 = 0;
    let mut files: u64 = 0;
    let mut newest: Option<SystemTime> = None;
    let mut truncated = false;
    let mut stack: Vec<PathBuf> = vec![root.to_path_buf()];
    let mut visited: usize = 0;

    while let Some(dir) = stack.pop() {
        let entries = match std::fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(error) => {
                // The first pop is the root, and whether the root is gone is a
                // fact about the directory rather than about this walk. `visited`
                // is still 0 there: nothing has been counted yet.
                if visited == 0 && error.kind() == std::io::ErrorKind::NotFound {
                    return Measurement::vanished();
                }
                // Everything else — a root that cannot be read, or a child that
                // disappeared part-way through — leaves the totals a partial sum.
                // A partial sum reads as a measurement, which is the thing D3
                // exists to prevent, so the walk ends the way a timeout ends.
                return Measurement::unknown();
            }
        };
        for entry in entries.flatten() {
            visited += 1;
            if visited > cap {
                truncated = true;
                break;
            }
            // `DirEntry::metadata` is `lstat`: a symlink is neither a dir nor a
            // file here, so it is counted as nothing and never followed.
            let Ok(meta) = entry.metadata() else {
                continue;
            };
            if meta.is_dir() {
                stack.push(entry.path());
            } else if meta.is_file() {
                files += 1;
                bytes = bytes.saturating_add(meta.len());
                if let Ok(mtime) = meta.modified() {
                    newest = Some(newest.map_or(mtime, |current| current.max(mtime)));
                }
            }
        }
        if truncated {
            break;
        }
    }

    if truncated {
        return Measurement::unknown();
    }
    Measurement {
        bytes: Some(bytes),
        files,
        newest,
        vanished: false,
    }
}

