//! Artifact scanning and boundary detection (product plan section 5.2).
//!
//! A directory name is only a **hint** (D7): a `build/` may hold tracked sources, a
//! `node_modules` may be a symlink into a shared store, and a `dist/` may hold
//! hand-written files. Every verdict therefore rests on facts this module can
//! verify — Git tracking, Git ignore status, nested repositories, symlink targets,
//! emptiness, and activity — and a fact that cannot be established produces
//! `af.cannot_verify` at `Review` instead of a guess (D3).
//!
//! Two boundaries are structural rather than checked:
//!
//! - the walk starts at each **worktree root** reported by Git, so `node_modules`
//!   is never mistaken for a project root and walked into (D8);
//! - the walk never descends into a recognised artifact directory, so an artifact
//!   nested inside another artifact is reported once, at its own path.
//!
//! Size measurement is the only filesystem walk, and it runs on a worker thread
//! with a timeout: an unmeasurable size stays `None` and must never be read as `0`
//! (development contract section 3). A size timeout does **not** downgrade the
//! verdict — the verdict rests on the Git facts, which stay cheap.

