/// The artifact kind a directory name maps to, or `None` when the name is not a
/// recognised artifact directory.
pub fn lookup_kind(name: &str) -> Option<&'static ArtifactKind> {
    ARTIFACT_KINDS.iter().find(|spec| spec.name == name)
}

/// Injection points for one artifact scan, mirroring
/// [`crate::worktree::WorktreeCheckOptions`]: everything that depends on the
/// clock, on a measurement, or on user policy is passed in, so the decision
/// logic is a pure function of the filesystem and of Git output.
#[derive(Debug, Clone)]
pub struct ArtifactScanOptions {
    /// How deep below a worktree root a candidate may sit (settings.max_depth).
    pub max_depth: usize,
    /// Budget for one size measurement (settings.per_dir_timeout_sec).
    pub per_dir_timeout: Duration,
    /// Activity window in days (settings.active_days).
    pub recent_activity_days: u32,
    /// Whitelist rules, already expanded to absolute paths by the caller.
    pub whitelist: Vec<PathBuf>,
    /// Injected clock, so "recent activity" is testable.
    pub now: SystemTime,
    /// When set, the scan stops adding artifacts once the budget is spent and
    /// reports the unscanned remainder as a warning instead of guessing.
    pub budget_deadline: Option<Instant>,
}

impl Default for ArtifactScanOptions {
    fn default() -> Self {
        Self {
            max_depth: 6,
            per_dir_timeout: Duration::from_secs(30),
            recent_activity_days: 7,
            whitelist: Vec::new(),
            now: SystemTime::now(),
            budget_deadline: None,
        }
    }
}

/// Result of one artifact scan.
pub struct ArtifactScanResult {
    pub records: Vec<ArtifactRecord>,
    /// Scanner-produced notes (a size measurement that timed out, a budget that
    /// ran out). They travel with the snapshot as data, not as UI chrome.
    pub warnings: Vec<String>,
}

/// Walks every worktree root and checks each recognised artifact directory.
///
/// `runner` answers the Git questions; the filesystem answers the rest. A root
/// that no longer exists (a prunable worktree) is skipped: there is nothing to
/// scan and nothing to delete.
pub fn scan_artifacts(
    runner: &dyn GitRunner,
    roots: &[PathBuf],
    opts: &ArtifactScanOptions,
) -> ArtifactScanResult {
    let mut records: Vec<ArtifactRecord> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let mut budget_spent = false;

    for root in roots {
        // A prunable worktree has no directory left, so it has no artifacts. Any
        // other stat failure is not evidence of absence, so only `NotFound`
        // skips (the same rule the worktree checks use).
        match std::fs::metadata(root) {
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
            Err(_) => continue,
        }

        for candidate in collect_candidates(root, opts.max_depth) {
            if let Some(deadline) = opts.budget_deadline {
                if Instant::now() >= deadline {
                    warnings.push(format!(
                        "the scan budget ran out; artifact scanning stopped at {} ({} directories checked so far)",
                        candidate.path.display(),
                        records.len()
                    ));
                    budget_spent = true;
                    break;
                }
            }
            let Some(spec) = lookup_kind(&candidate.name) else {
                continue;
            };
            let (record, mut notes) = check_artifact(runner, root, &candidate.path, spec, opts);
            warnings.append(&mut notes);
            records.push(record);
        }
        if budget_spent {
            break;
        }
    }

    ArtifactScanResult { records, warnings }
}

/// A directory whose name matched a recognised artifact kind.
struct Candidate {
    path: PathBuf,
    name: String,
}

/// Upper bound on directory entries visited per worktree root. A repository with
/// more entries than this is not scanned completely, and the measurement reports
/// `None` rather than a partial number that would look exact.
const MAX_WALK_ENTRIES: usize = 2_000_000;

/// Collects artifact candidate directories under `root`, breadth-first by depth.
///
/// The walk never enters `.git` and never descends into a recognised artifact
/// directory: `node_modules/.bin` is not a second artifact, and `node_modules`
/// is never treated as a project root (D8).
fn collect_candidates(root: &Path, max_depth: usize) -> Vec<Candidate> {
    let mut out: Vec<Candidate> = Vec::new();
    let mut stack: Vec<(PathBuf, usize)> = vec![(root.to_path_buf(), 0)];
    let mut visited: usize = 0;

    while let Some((dir, depth)) = stack.pop() {
        let entries = match std::fs::read_dir(&dir) {
            Ok(entries) => entries,
            // An unreadable directory is not evidence that nothing is inside it.
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            visited += 1;
            if visited > MAX_WALK_ENTRIES {
                return out;
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            let path = entry.path();
            // `DirEntry::metadata` does not follow symlinks, which is what the
            // symlink checks below need.
            let is_dir = entry.metadata().map(|meta| meta.is_dir()).unwrap_or(false);

            if lookup_kind(&name).is_some() {
                out.push(Candidate { path, name });
                continue;
            }
            if is_dir && name != ".git" && name != ".hg" && name != ".svn" && depth < max_depth {
                stack.push((path, depth + 1));
            }
        }
    }
    out
}

/// Checks one candidate directory and assembles its [`ArtifactRecord`].
///
/// Returns the record together with scanner notes (an unmeasurable size). The
/// verdict is derived from the reasons by [`SafetyAssessment::from_reasons`]
/// (D2); this function never scores a level on its own.
pub fn check_artifact(
    runner: &dyn GitRunner,
    root: &Path,
    dir: &Path,
    spec: &ArtifactKind,
    opts: &ArtifactScanOptions,
) -> (ArtifactRecord, Vec<String>) {
    let mut reasons: Vec<Reason> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let dir_text = dir.display().to_string();

    // ---- symlink: never follow, never delete through the link ----
    let link_meta = std::fs::symlink_metadata(dir);
    let is_symlink = link_meta
        .as_ref()
        .map(|m| m.file_type().is_symlink())
        .unwrap_or(false);
    let mut symlink_target: Option<String> = None;
    if is_symlink {
        let target = std::fs::canonicalize(dir).ok();
        let root_resolved = std::fs::canonicalize(root).unwrap_or_else(|_| root.to_path_buf());
        match target {
            Some(target) if !target.starts_with(&root_resolved) => {
                symlink_target = Some(target.display().to_string());
                reasons.push(Reason::blocking(
                    ReasonCode::AfSymlinkOutside,
                    "symlink pointing outside the project",
                    format!(
                        "target {} is outside the project root {}; deleting it would damage a shared directory",
                        target.display(),
                        root.display()
                    ),
                ));
            }
            Some(target) => {
                symlink_target = Some(target.display().to_string());
                reasons.push(Reason::review(
                    ReasonCode::AfCannotVerify,
                    "could not complete the check",
                    format!(
                        "symlink target {} is inside the project; deleting the link does not remove the target",
                        target.display()
                    ),
                ));
            }
            None => {
                reasons.push(Reason::review(
                    ReasonCode::AfCannotVerify,
                    "could not complete the check",
                    format!("the symlink target of {} cannot be resolved", dir_text),
                ));
            }
        }
    }

    // ---- whitelist: a rule protects the path completely ----
    if let Some(rule) = whitelist_hit(dir, &opts.whitelist) {
        reasons.push(Reason::blocking(
            ReasonCode::AfWhitelisted,
            "protected by a whitelist rule",
            format!("matches the whitelist rule {}", rule.display()),
        ));
    }

    // ---- nested repository: deleting it would destroy history ----
    if !is_symlink && dir.join(".git").exists() {
        reasons.push(Reason::blocking(
            ReasonCode::AfNestedGit,
            "contains a nested Git repository",
            "a .git directory was found inside; deleting it would destroy that repository's history",
        ));
    }

    // ---- Git tracking: tracked content is not a build artifact (D7) ----
    let mut git_tracked: Option<bool> = None;
    if !is_symlink {
        match runner.run(root, &["ls-files", "--", &dir_text]) {
            Ok(output) if output.success() => {
                let tracked = output
                    .stdout
                    .lines()
                    .filter(|line| !line.trim().is_empty())
                    .count();
                git_tracked = Some(tracked > 0);
                if tracked > 0 {
                    reasons.push(Reason::blocking(
                        ReasonCode::AfGitTracked,
                        "the directory contains files committed to the repository",
                        format!("git ls-files matches {tracked} files, so it is not a pure build artifact"),
                    ));
                }
            }
            Ok(output) => reasons.push(cannot_verify(&format!(
                "git ls-files exited with {:?}: {}",
                output.code,
                output.stderr.trim()
            ))),
            Err(error) => reasons.push(cannot_verify(&format!("git ls-files failed: {error}"))),
        }
    }

    // ---- Git ignore status ----
    let mut git_ignored: Option<bool> = None;
    if !is_symlink {
        match runner.run(root, &["check-ignore", "-v", "--", &dir_text]) {
            Ok(output) if output.success() => {
                git_ignored = Some(true);
                let evidence = parse_ignore_source(&output.stdout)
                    .unwrap_or_else(|| "git check-ignore reports it as ignored".to_string());
                reasons.push(Reason::safe(
                    ReasonCode::AfGitIgnored,
                    "ignored by .gitignore",
                    evidence,
                ));
            }
            // Exit 1 means "not ignored", which is a real answer, not a failure.
            Ok(output) if output.code == Some(1) => git_ignored = Some(false),
            Ok(output) => reasons.push(cannot_verify(&format!(
                "git check-ignore exited with {:?}: {}",
                output.code,
                output.stderr.trim()
            ))),
            Err(error) => reasons.push(cannot_verify(&format!("git check-ignore failed: {error}"))),
        }
    }

    // ---- authored content: a generic name holding hand-written files ----
    if spec.generic_name && !is_symlink && git_tracked != Some(true) {
        match runner.run(
            root,
            &[
                "status",
                "--porcelain",
                "--untracked-files=all",
                "--",
                &dir_text,
            ],
        ) {
            Ok(output) if output.success() => {
                // `--porcelain` (v1) marks an untracked entry with `??`; the
                // `? ` form belongs to `--porcelain=v2` and would never match
                // here, silently disabling this check.
                let untracked = output
                    .stdout
                    .lines()
                    .filter(|line| line.starts_with("??"))
                    .count();
                if untracked > 0 {
                    reasons.push(Reason::blocking(
                        ReasonCode::AfAuthoredContent,
                        "contains hand-written content",
                        format!(
                            "{untracked} files inside are neither tracked by Git nor ignored; they look like authored content"
                        ),
                    ));
                }
            }
            Ok(output) => reasons.push(cannot_verify(&format!(
                "git status exited with {:?}: {}",
                output.code,
                output.stderr.trim()
            ))),
            Err(error) => reasons.push(cannot_verify(&format!("git status failed: {error}"))),
        }
    }

    // ---- size, file count, and newest modification ----
    let measurement = if is_symlink {
        // Never walk through a symlink: the target may be a shared store whose
        // size says nothing about this project.
        Measurement::unknown()
    } else {
        measure_dir(dir, opts.per_dir_timeout)
    };
    if measurement.bytes.is_none() && !is_symlink {
        warnings.push(format!(
            "size measurement of {} did not complete within {}s; the size is recorded as unknown",
            dir_text,
            opts.per_dir_timeout.as_secs()
        ));
    }
    let last_updated_at = measurement.newest.map(format_rfc3339);

    // ---- emptiness ----
    if !is_symlink && measurement.files == 0 {
        reasons.push(Reason::safe(
            ReasonCode::AfEmpty,
            "the directory is empty",
            "it contains no files",
        ));
    }

    // ---- rebuildability ----
    if spec.rebuild_markers.is_empty() {
        reasons.push(Reason::safe(
            ReasonCode::AfRebuildable,
            "regenerable directory",
            spec.rebuild_how.to_string(),
        ));
    } else {
        let found = spec
            .rebuild_markers
            .iter()
            .find(|marker| root.join(marker).exists());
        match found {
            Some(marker) => reasons.push(Reason::safe(
                ReasonCode::AfRebuildable,
                "regenerable directory",
                format!("{marker} exists; {}", spec.rebuild_how),
            )),
            None => reasons.push(Reason::review(
                ReasonCode::AfCannotVerify,
                "could not complete the check",
                format!(
                    "no build manifest ({}) at the project root; cannot confirm the directory is regenerable",
                    spec.rebuild_markers.join(" / ")
                ),
            )),
        }
    }

    // ---- activity ----
    if let Some(newest) = measurement.newest {
        let age_days = elapsed_days(opts.now, newest);
        if age_days <= opts.recent_activity_days as u64 {
            reasons.push(Reason::review(
                ReasonCode::AfRecentActivity,
                "changed recently",
                format!("last activity: {}", humanize_days(age_days)),
            ));
        }
    }

    let record = ArtifactRecord {
        path: dir_text,
        kind: spec.kind.to_string(),
        ecosystem: spec.ecosystem.to_string(),
        project_root: root.display().to_string(),
        worktree_path: Some(root.display().to_string()),
        size_bytes: measurement.bytes,
        file_count: measurement.files,
        last_updated_at,
        git_ignored,
        git_tracked,
        is_symlink,
        symlink_target,
        safety: SafetyAssessment::from_reasons(reasons),
    };
    (record, warnings)
}

/// A `cannot_verify` reason for an artifact check that could not be completed.
fn cannot_verify(evidence: &str) -> Reason {
    Reason::review(
        ReasonCode::AfCannotVerify,
        "could not complete the check",
        evidence.to_string(),
    )
}

/// Parses `git check-ignore -v` output (`<source>:<line>:<pattern>\t<path>`) into
/// the `.gitignore:12` form the UI shows as evidence.
fn parse_ignore_source(stdout: &str) -> Option<String> {
    let line = stdout.lines().next()?;
    let (source, _rest) = line.split_once('\t')?;
    let mut parts = source.splitn(3, ':');
    let file = parts.next()?;
    let number = parts.next()?;
    if file.is_empty() || number.is_empty() {
        return None;
    }
    Some(format!("{file}:{number}"))
}

/// One size measurement.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Measurement {
    /// `None` = unmeasurable (timeout or an entry-count cap), which must stay
    /// distinguishable from `0` (development contract section 3).
    pub bytes: Option<u64>,
    /// File count; `0` also covers "not counted", which the UI shows as unknown.
    pub files: u64,
    /// Newest modification time seen, when the walk completed.
    pub newest: Option<SystemTime>,
}

impl Measurement {
    fn unknown() -> Self {
        Self {
            bytes: None,
            files: 0,
            newest: None,
        }
    }
}

/// Measures a directory on a worker thread with a timeout.
///
/// The worker is abandoned when the budget expires: the numbers it would report
/// are unknown, and a partial sum would look exact (D3). Symlinks are never
/// followed, so a link cycle cannot make the walk run forever.
pub fn measure_dir(path: &Path, timeout: Duration) -> Measurement {
    let (sender, receiver) = mpsc::channel();
    let owned = path.to_path_buf();
    let worker = std::thread::spawn(move || {
        let _ = sender.send(walk_size(&owned));
    });
    let measurement = match receiver.recv_timeout(timeout) {
        Ok(measurement) => measurement,
        // The worker keeps running in the background and its result is dropped:
        // reporting a partial size would be worse than reporting none.
        Err(_) => Measurement::unknown(),
    };
    // Joining would block for as long as the walk takes, which is exactly what
    // the timeout exists to avoid; the thread holds no borrowed state.
    drop(worker);
    measurement
}

fn walk_size(root: &Path) -> Measurement {
    walk_size_with_cap(root, MAX_WALK_ENTRIES)
}

/// The entry cap is a parameter so the over-limit branch can be exercised by a
/// three-entry fixture instead of a two-million-entry one.
fn walk_size_with_cap(root: &Path, cap: usize) -> Measurement {
    let mut bytes: u64 = 0;
    let mut files: u64 = 0;
    let mut newest: Option<SystemTime> = None;
    let mut truncated = false;
    let mut stack: Vec<PathBuf> = vec![root.to_path_buf()];
    let mut visited: usize = 0;

    while let Some(dir) = stack.pop() {
        let entries = match std::fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            visited += 1;
            if visited > cap {
                truncated = true;
                break;
            }
            // `DirEntry::metadata` is `lstat`: a symlink is neither a dir nor a
            // file here, so it is counted as nothing and never followed.
            let meta = match entry.metadata() {
                Ok(meta) => meta,
                Err(_) => continue,
            };
            if meta.is_dir() {
                stack.push(entry.path());
            } else if meta.is_file() {
                files += 1;
                bytes = bytes.saturating_add(meta.len());
                if let Ok(mtime) = meta.modified() {
                    newest = Some(newest.map_or(mtime, |current| current.max(mtime)));
                }
            }
        }
        if truncated {
            break;
        }
    }

    if truncated {
        return Measurement::unknown();
    }
    Measurement {
        bytes: Some(bytes),
        files,
        newest,
    }
}

